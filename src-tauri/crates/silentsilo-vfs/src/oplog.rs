    // ---- convergence: the property the whole design exists for ----

    /// Deterministic pseudo-randomness for the property test below.
    ///
    /// A generator rather than a dependency, so a failure is reproducible
    /// from the seed printed with it and the crate keeps the dependency list
    /// it has. Values are only ever used to choose shapes, never as keys.
    struct Rng(u64);

    impl Rng {
        fn next(&mut self) -> u64 {
            // Numerical Recipes' LCG constants.
            self.0 = self
                .0
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            self.0 >> 11
        }

        fn below(&mut self, n: usize) -> usize {
            (self.next() % n as u64) as usize
        }

        /// A uuid from the generator, so a failing seed rebuilds the same ids.
        fn uuid(&mut self) -> Uuid {
            Uuid::from_u128(((self.next() as u128) << 64) | self.next() as u128)
        }
    }

    /// A batch of operations from several devices, touching shared entities.
    ///
    /// The ids come from a small pool on purpose: operations that name
    /// entities nobody else touches converge trivially, and prove nothing.
    fn generated_batch(rng: &mut Rng, root: Uuid) -> Vec<OpRecord> {
        let devices: Vec<Uuid> = (0..3).map(|_| rng.uuid()).collect();
        let folders: Vec<Uuid> = (0..4).map(|_| rng.uuid()).collect();
        let names = ["Shared", "Team", "Archive", "2026"];
        // Small pools, so edits actually land on the same file and claim to
        // replace content another edit has already replaced. Drawn wide and
        // the interesting case never happens.
        let mut files: Vec<Uuid> = Vec::new();
        let blobs: Vec<Uuid> = (0..3).map(|_| rng.uuid()).collect();

        // Per-device counters, so records at least carry a plausible chain.
        // The fingerprints are left out: convergence is what this generates
        // for, and `replay` never reads them. `verify_chains` has its own
        // tests.
        let mut seqs: std::collections::HashMap<Uuid, u64> = std::collections::HashMap::new();
        let mut next_seq = |device: Uuid| {
            let seq = seqs.entry(device).or_insert(0);
            let current = *seq;
            *seq += 1;
            current
        };

        let mut batch = Vec::new();
        for i in 0..rng.below(14) + 6 {
            let device = devices[rng.below(devices.len())];
            let folder = folders[rng.below(folders.len())];
            let name = names[rng.below(names.len())];
            // Lamport values deliberately collide across devices: that is the
            // case the device-id tiebreak exists for.
            let lamport = (i as u64 / 2) + 1;

            let op = match rng.below(9) {
                0 => new_folder(folder, root, name),
                1 => new_folder(folder, folders[rng.below(folders.len())], name),
                2 => add_file(rng.uuid(), folder, &format!("{name}.txt")),
                3 => VaultOp::RenameFolder {
                    id: folder,
                    name: name.into(),
                },
                4 => VaultOp::TrashFolder { id: folder },
                5 => VaultOp::RestoreFolder { id: folder },
                6 => {
                    // Remembered, so the edits below have a real file to
                    // land on. Ids stay unique because the app mints one per
                    // import and never reuses them.
                    let id = rng.uuid();
                    files.push(id);
                    VaultOp::AddFile {
                        id,
                        folder_id: folder,
                        name: format!("{name}.bin"),
                        blob_id: blobs[rng.below(blobs.len())],
                        size_bytes: 1,
                        content_hash: "h".into(),
                        mime_type: None,
                        blob_key: String::new(),
                    }
                }
                // Content edits claiming to replace a blob another edit may
                // already have replaced, which is what makes a conflict
                // copy. Every device must reach the same pair of entries
                // whichever order the records arrive in.
                7 if !files.is_empty() => VaultOp::ReplaceFileContent {
                    id: files[rng.below(files.len())],
                    blob_id: rng.uuid(),
                    size_bytes: 2,
                    content_hash: "h2".into(),
                    mime_type: None,
                    replaces: Some(blobs[rng.below(blobs.len())]),
                    blob_key: String::new(),
                },
                7 => add_file(rng.uuid(), folder, &format!("{name}.txt")),
                _ => {
                    // An operation from a future build. Marked skippable, so
                    // every device must reach the same place whether or not
                    // it understands the record.
                    batch.push(OpRecord {
                        op_id: rng.uuid(),
                        lamport,
                        device_id: device,
                        at: 1_700_000_000,
                        skippable: true,
                        seq: next_seq(device),
                        prev: None,
                        op: OpBody::Unknown {
                            op: "SomethingLater".into(),
                            fields: serde_json::Map::new(),
                        },
                    });
                    continue;
                }
            };
            batch.push(OpRecord::authored(
                rng.uuid(),
                lamport,
                device,
                1_700_000_000,
                next_seq(device),
                None,
                op,
            ));
        }
        batch
    }

    fn shuffled(rng: &mut Rng, batch: &[OpRecord]) -> Vec<OpRecord> {
        let mut out = batch.to_vec();
        for i in (1..out.len()).rev() {
            out.swap(i, rng.below(i + 1));
        }
        out
    }

