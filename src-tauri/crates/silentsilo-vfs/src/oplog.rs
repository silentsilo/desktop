    #[test]
    fn any_arrival_order_converges() {
        // Every seed builds one batch, hands it to four devices in four
        // different orders, and requires identical trees. Run with 20000
        // seeds by hand after touching anything in the naming path.
        for seed in 0..1000u64 {
            let mut rng = Rng(seed.wrapping_mul(0x9E3779B97F4A7C15) | 1);
            let vault = Uuid::new_v4();
            let root = crate::schema::root_folder_id_for(vault);
            let reference = bare_device(vault);
            let batch = generated_batch(&mut rng, root);

            replay(&reference, batch.clone())
                .unwrap_or_else(|e| panic!("seed {seed}: replay failed: {e}"));
            let expected = snapshot_of(&reference);

            for attempt in 0..4 {
                let other = bare_device(vault);
                replay(&other, shuffled(&mut rng, &batch))
                    .unwrap_or_else(|e| panic!("seed {seed}, order {attempt}: replay failed: {e}"));
                assert_eq!(
                    snapshot_of(&other),
                    expected,
                    "seed {seed}, order {attempt}: devices disagree after the same {} operations",
                    batch.len()
                );
            }
        }
    }

    /// One file, and two devices that both edit it without seeing the other.
    fn concurrent_edits(a: &Device, b: &Device, root: Uuid) -> (Uuid, Uuid, Vec<OpRecord>) {
        let file = Uuid::new_v4();
        let original = Uuid::new_v4();
        let from_a = Uuid::new_v4();
        let from_b = Uuid::new_v4();

        let records = vec![
            a.make(
                1,
                VaultOp::AddFile {
                    id: file,
                    folder_id: root,
                    name: "report.pdf".into(),
                    blob_id: original,
                    size_bytes: 10,
                    content_hash: "one".into(),
                    mime_type: None,
                    blob_key: String::new(),
                },
            ),
            // Both write on top of the same content, which is what makes
            // this concurrent rather than sequential.
            a.make(
                2,
                VaultOp::ReplaceFileContent {
                    id: file,
                    blob_id: from_a,
                    size_bytes: 20,
                    content_hash: "a".into(),
                    mime_type: None,
                    replaces: Some(original),
                    blob_key: String::new(),
                },
            ),
            b.make(
                2,
                VaultOp::ReplaceFileContent {
                    id: file,
                    blob_id: from_b,
                    size_bytes: 30,
                    content_hash: "b".into(),
                    mime_type: None,
                    replaces: Some(original),
                    blob_key: String::new(),
                },
            ),
        ];
        (from_a, from_b, records)
    }

    /// Id included on purpose. A conflict copy is derived state, not an
    /// operation, so each device builds its own: if two devices give theirs
    /// different ids, a later rename or trash naming one of them resolves on
    /// one device and is ignored as obsolete on the other, and they never
    /// agree again.
    fn blobs_in(conn: &Connection) -> Vec<(String, String, String)> {
        let mut stmt = conn
            .prepare("SELECT id, name, blob_id FROM files ORDER BY name")
            .unwrap();
        let rows = stmt
            .query_map([], |r| {
                Ok((
                    r.get::<_, String>(0)?,
                    r.get::<_, String>(1)?,
                    r.get::<_, String>(2)?,
                ))
            })
            .unwrap();
        rows.map(|r| r.unwrap()).collect()
    }

