    // ── The index is a cache ────────────────────────────────────────────
    // The derived tables are a function of the log, so dropping and
    // replaying them is always safe. These tests defend that property.

    /// Wider than `Device::snapshot`, which only compares tree shape between
    /// devices. A rebuild has to reproduce everything, including the columns
    /// convergence tests never look at.
    fn full_digest(conn: &Connection) -> Vec<String> {
        let mut out = Vec::new();
        for (label, sql) in [
            (
                "folder",
                "SELECT path || ' deleted=' || (deleted_at IS NOT NULL) || ' fav=' || favorite
                   FROM folders ORDER BY path",
            ),
            (
                "file",
                "SELECT fo.path || '::' || f.name || ' deleted=' || (f.deleted_at IS NOT NULL)
                        || ' fav=' || f.favorite || ' blob=' || f.blob_id
                        || ' size=' || f.size_bytes || ' hash=' || f.content_hash
                   FROM files f JOIN folders fo ON fo.id = f.folder_id
                  ORDER BY fo.path, f.name",
            ),
            (
                "password",
                "SELECT id || ' ' || data FROM passwords ORDER BY id",
            ),
            (
                "device",
                "SELECT device_id || ' ' || label || ' ' || COALESCE(platform, '')
                   FROM device_labels ORDER BY device_id",
            ),
            (
                "claim",
                "SELECT entry_id || ' ' || desired || ' ' || lamport
                   FROM name_claims ORDER BY entry_id",
            ),
        ] {
            let mut stmt = conn.prepare(sql).unwrap();
            let rows = stmt.query_map([], |r| r.get::<_, String>(0)).unwrap();
            for row in rows {
                out.push(format!("{label} {}", row.unwrap()));
            }
        }
        out
    }

    /// A silo with something of every kind in it, so a rebuild has more to
    /// get wrong than a flat list of files.
    fn populate(d: &Device) {
        let root = d.root();
        let docs = Uuid::new_v4();
        let nested = Uuid::new_v4();
        let keep = Uuid::new_v4();
        let trashed = Uuid::new_v4();
        let replaced = Uuid::new_v4();

        let ops = vec![
            new_folder(docs, root, "Docs"),
            new_folder(nested, docs, "2026"),
            add_file(keep, docs, "contract.pdf"),
            add_file(trashed, nested, "old.txt"),
            add_file(replaced, root, "notes.md"),
            VaultOp::ReplaceFileContent {
                id: replaced,
                blob_id: Uuid::new_v4(),
                size_bytes: 99,
                content_hash: "second".into(),
                mime_type: Some("text/markdown".into()),
                replaces: None,
                blob_key: String::new(),
            },
            VaultOp::TrashFile { id: trashed },
            VaultOp::SetFileFavorite {
                id: keep,
                favorite: true,
            },
            VaultOp::SetFolderFavorite {
                id: docs,
                favorite: true,
            },
            VaultOp::UpsertPassword {
                id: Uuid::new_v4(),
                data: "sealed-bank".into(),
            },
            VaultOp::AnnounceDevice {
                subject: d.id,
                system_name: Some("workstation".into()),
                platform: "windows".into(),
            },
            VaultOp::SetDeviceLabel {
                subject: d.id,
                label: "Desk".into(),
            },
        ];

        for op in ops {
            let record = d.make(next_lamport(d.conn()).unwrap(), op);
            apply_op(d.conn(), &record).unwrap();
        }
    }

    #[test]
    fn dropping_the_derived_tables_and_replaying_reproduces_the_vault() {
        let d = Device::new();
        populate(&d);
        let before = full_digest(d.conn());
        assert!(before.len() > 10, "the corpus must actually cover things");

        crate::schema::drop_derived_for_test(d.conn()).unwrap();
        crate::schema::init_schema(d.conn(), d.session.vault_id).unwrap();
        rebuild_derived(d.conn()).unwrap();

        assert_eq!(before, full_digest(d.conn()));
    }

    #[test]
    fn a_schema_version_mismatch_rebuilds_by_itself() {
        // The whole point: a future build reading a database written by an
        // older schema must recover without anyone calling anything special.
        let d = Device::new();
        populate(&d);
        let before = full_digest(d.conn());

        d.conn()
            .execute(
                "UPDATE vault_meta SET value = '0' WHERE key = 'schema_version'",
                [],
            )
            .unwrap();

        crate::schema::init_schema(d.conn(), d.session.vault_id).unwrap();

        assert_eq!(before, full_digest(d.conn()));
        let stored: String = d
            .conn()
            .query_row(
                "SELECT value FROM vault_meta WHERE key = 'schema_version'",
                [],
                |r| r.get(0),
            )
            .unwrap();
        assert_eq!(stored, crate::schema::SCHEMA_VERSION.to_string());
    }

    #[test]
    fn a_silo_that_never_saw_a_bucket_can_still_be_rebuilt() {
        // The case with no second copy anywhere. Before the log held its
        // payloads, this vault's history existed only as the derived rows,
        // and a schema change would have been unrecoverable.
        let d = Device::new();
        let vfs = Vfs::new(&d.session);
        let root = vfs.root_folder_id().unwrap();
        vfs.create_folder(root, "Acte").unwrap();
        vfs.create_folder(root, "Facturi").unwrap();

        assert_eq!(
            pending_count(d.conn()).unwrap(),
            2,
            "nothing has been pushed, so both records are still owed to storage"
        );
        let before = full_digest(d.conn());

        crate::schema::drop_derived_for_test(d.conn()).unwrap();
        crate::schema::init_schema(d.conn(), d.session.vault_id).unwrap();
        rebuild_derived(d.conn()).unwrap();

        assert_eq!(before, full_digest(d.conn()));
        assert_eq!(
            pending_count(d.conn()).unwrap(),
            2,
            "a rebuild must not lose what storage has not got yet"
        );
    }

    #[test]
    fn a_pushed_record_stays_in_the_log() {
        // `clear_pushed` used to delete the row. It cannot any more: that
        // row is the only local copy of the operation's payload.
        let d = Device::new();
        let vfs = Vfs::new(&d.session);
        let root = vfs.root_folder_id().unwrap();
        vfs.create_folder(root, "Acte").unwrap();

        let queued = pending_ops(d.conn()).unwrap();
        assert_eq!(queued.len(), 1);
        clear_pushed(d.conn(), &queued).unwrap();

        assert_eq!(pending_count(d.conn()).unwrap(), 0);
        assert_eq!(
            all_ops(d.conn()).unwrap().len(),
            1,
            "pushed means recorded as sent, not forgotten"
        );

        let before = full_digest(d.conn());
        crate::schema::drop_derived_for_test(d.conn()).unwrap();
        crate::schema::init_schema(d.conn(), d.session.vault_id).unwrap();
        rebuild_derived(d.conn()).unwrap();
        assert_eq!(before, full_digest(d.conn()));
    }

    #[test]
    fn the_log_keeps_records_arriving_from_other_devices() {
        // A joining device holds no payload of its own. If replay recorded
        // only identities, its vault would be unrebuildable the moment the
        // bucket went away.
        let vault = Uuid::new_v4();
        let source = Device::joining(vault);
        populate(&source);

        let mirror = Device::joining(vault);
        replay(mirror.conn(), all_ops(source.conn()).unwrap()).unwrap();
        let before = full_digest(mirror.conn());

        crate::schema::drop_derived_for_test(mirror.conn()).unwrap();
        crate::schema::init_schema(mirror.conn(), vault).unwrap();
        rebuild_derived(mirror.conn()).unwrap();

        assert_eq!(before, full_digest(mirror.conn()));
        assert_eq!(
            pending_count(mirror.conn()).unwrap(),
            0,
            "records that arrived from storage are not owed back to it"
        );
    }
